    private void cargarComboPlanes() {
    cmbplanalimentacion.removeAllItems();
    List<PlanAlimentacion> planes = planDAO.listarTodos();
    for (PlanAlimentacion p : planes) {
        cmbplanalimentacion.addItem(p.getNombre()); // solo nombres
    }
        cmbplanalimentacion.setSelectedIndex(-1); // nada seleccionado por defecto
    }
    
    private void cargarTablaDietas() {
        controlador.cargarTabla(tabladieta);
    }
    
    private void limpiarCampos() {
        txtiddieta.setText("");
        cmbnombre.setSelectedIndex(0);
        cmbplanalimentacion.setSelectedIndex(-1);
        txtingrediente.setText("");
        txtcantidad.setText("");
    }
    
    private void tablaClick() {
        int fila = tabladieta.getSelectedRow();
        if (fila >= 0) {
            txtiddieta.setText(tabladieta.getValueAt(fila, 0).toString());
            txtingrediente.setText(tabladieta.getValueAt(fila, 3).toString());
            txtcantidad.setText(tabladieta.getValueAt(fila, 4).toString());
        }
    }
    
