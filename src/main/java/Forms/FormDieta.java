    private void btnagregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagregarActionPerformed
              
        try {
            
            // Validación de combobox
            if (cmbplanalimentacion.getSelectedIndex() == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un plan de alimentación.");
                return;
            }
            if (cmbnombre.getSelectedIndex() == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un nombre de dieta (Desayuno, Almuerzo, Cena).");
                return;
            }
            
            String nombrePlan = (String) cmbplanalimentacion.getSelectedItem();
            if (nombrePlan == null) {
                JOptionPane.showMessageDialog(this, "Seleccione un plan de alimentación.");
                return;
            }
            PlanAlimentacion plan = planDAO.buscarPorNombre(nombrePlan);

            DietaCliente dieta = new DietaCliente();
            dieta.setNombre(cmbnombre.getSelectedItem().toString());
            dieta.setIngrediente(txtingrediente.getText().trim());
            dieta.setCantidad(txtcantidad.getText().trim());
            dieta.setPlan(plan);

            if (controlador.guardarDieta(dieta)) {
                JOptionPane.showMessageDialog(this, "Dieta agregada correctamente.");
                cargarTablaDietas();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "Datos inválidos.");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnagregarActionPerformed

    private void btnmodificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnmodificarActionPerformed
       
       try {
           
           // Validación de combobox
            if (cmbplanalimentacion.getSelectedIndex() == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un plan de alimentación.");
                return;
            }
            if (cmbnombre.getSelectedIndex() == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un nombre de dieta (Desayuno, Almuerzo, Cena).");
                return;
            }
           
            int id = Integer.parseInt(txtiddieta.getText());
            DietaCliente dieta = controlador.obtenerPorId(id);
            if (dieta == null) return;

            String nombrePlan = (String) cmbplanalimentacion.getSelectedItem();
            PlanAlimentacion plan = planDAO.buscarPorNombre(nombrePlan);

            dieta.setNombre(cmbnombre.getSelectedItem().toString());
            dieta.setIngrediente(txtingrediente.getText().trim());
            dieta.setCantidad(txtcantidad.getText().trim());
            dieta.setPlan(plan);

            if (controlador.actualizarDieta(dieta)) {
                JOptionPane.showMessageDialog(this, "Dieta modificada correctamente.");
                cargarTablaDietas();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "Datos inválidos.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Seleccione una dieta de la tabla.");
        }
    }//GEN-LAST:event_btnmodificarActionPerformed

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
        try {
            int id = Integer.parseInt(txtiddieta.getText());
            controlador.eliminarDieta(id);
            JOptionPane.showMessageDialog(this, "Dieta eliminada correctamente.");
            cargarTablaDietas();
            limpiarCampos();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Seleccione una dieta de la tabla.");
        }
    }//GEN-LAST:event_btneliminarActionPerformed

